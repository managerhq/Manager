        private static string Get(string key)
        {
            if (CurrentLanguage.Value == null) return null;
            if (key == null) return null;
            return translations.GetValueOrDefault(CurrentLanguage.Value)?.GetValueOrDefault(key);
        }

        public static string GetPropertyValue(Type type)
        {
            var name = ManagerServer.Globalization.Strings.GetPropertyValue(type.Name);
            if (type.IsNested) name = ManagerServer.Globalization.Strings.GetPropertyValue(type.DeclaringType.Name) + " - " + name;
            return name;
        }

        public static string GetPropertyValue(string name)
        {
            if (string.IsNullOrWhiteSpace(name)) return name;
            var property = typeof(Strings).GetProperty(name, System.Reflection.BindingFlags.Static | System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.IgnoreCase);
            if (property == null) return name;
            return (string)property.GetValue(null);
        }

